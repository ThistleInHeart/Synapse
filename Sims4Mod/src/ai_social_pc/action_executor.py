def _handle_money_action(actor_name: str, action_clean: str, host_sim_info: Any, recipient_sim_info: Any, feedback_fn: Any = None):
    """
    Handles transferring simoleons between player household and interlocutor Sim.
    Supports send_money, borrow_money, receive_money, give_money, loan with optional amount (e.g. [DO=send_money:500]).
    """
    import re
    is_en = _is_en()
    try:
        active_sim_info = services.active_sim_info() if hasattr(services, "active_sim_info") else None
        host_info = active_sim_info or host_sim_info
        if host_info is None:
            return

        household = host_info.household if hasattr(host_info, "household") else None
        if household is None or not hasattr(household, "funds"):
            return

        funds = household.funds
        cur_money = getattr(funds, "money", 0)

        # Parse amount from action string (e.g. "send_money:500" or "borrow_money_1000")
        amount = 500
        amt_match = re.search(r'[:_](\d+)', action_clean)
        if amt_match:
            try:
                parsed_amt = int(amt_match.group(1))
                if parsed_amt > 0:
                    amount = parsed_amt
            except Exception:
                amount = 500

        # Determine other participant Sim
        other_info = None
        if recipient_sim_info is not None and getattr(recipient_sim_info, "sim_id", 0) != getattr(host_info, "sim_id", 0):
            other_info = recipient_sim_info
        elif actor_name:
            other_info = _resolve_sim_info_by_name(actor_name, host_info, recipient_sim_info)

        other_name = "Собеседник" if not is_en else "Friend"
        if other_info is not None:
            fn = getattr(other_info, "first_name", "") or ""
            ln = getattr(other_info, "last_name", "") or ""
            other_name = f"{fn} {ln}".strip() or other_name

        # Determine direction:
        # If action is 'borrow_money' or 'take_loan' -> player receives money (+amount) if player borrowed,
        # OR if WHODO is other sim asking player for loan -> player lends money (-amount).
        is_player_paying = False
        act_base = action_clean.split(":")[0].strip()

        is_actor_host = False
        if actor_name and host_info:
            hf = (getattr(host_info, "first_name", "") or "").lower()
            hl = (getattr(host_info, "last_name", "") or "").lower()
            hfull = f"{hf} {hl}".strip()
            an_lower = actor_name.lower()
            if an_lower in hfull or an_lower == hf:
                is_actor_host = True

        if act_base in ("borrow_money", "ask_loan", "take_loan"):
            is_player_paying = not is_actor_host
        elif act_base in ("send_money", "give_money", "pay_money", "transfer_money"):
            is_player_paying = is_actor_host
        elif act_base in ("receive_money", "get_money"):
            is_player_paying = False
        else:
            is_player_paying = is_actor_host

        host_sim = host_info.get_sim_instance(allow_hidden_flags=ALL_HIDDEN_REASONS) if hasattr(host_info, "get_sim_instance") else None

        reason = 0
        try:
            from protocolbuffers import Consts_pb2
            reason = getattr(Consts_pb2, "TELEMETRY_MONEY_CHEAT", 0)
        except Exception:
            pass

        if is_player_paying:
            # Deduct money from household
            if cur_money < amount:
                title = "Недостаточно средств" if not is_en else "Insufficient Funds"
                msg = (
                    f"На счету семьи недостаточно симолеонов для перевода ({amount} §). Текущий баланс: {cur_money} §."
                    if not is_en else
                    f"Not enough simoleons in household funds ({amount} §). Current balance: {cur_money} §."
                )
                show_chat_notification(title, msg, is_error=True)
                if feedback_fn:
                    feedback_fn(msg)
                return

            if hasattr(funds, "remove"):
                try:
                    funds.remove(amount, reason, host_sim)
                except TypeError:
                    funds.remove(amount, reason)
            elif hasattr(funds, "modify_funds"):
                funds.modify_funds(-amount)

            new_bal = getattr(funds, "money", cur_money - amount)
            title = "💸 Денежный перевод" if not is_en else "💸 Money Transfer"
            msg = (
                f"Вы перевели {other_name} {amount:,} §.\nНовый баланс семьи: {new_bal:,} §."
                if not is_en else
                f"You transferred {amount:,} § to {other_name}.\nNew household balance: {new_bal:,} §."
            )
            show_chat_notification(title, msg)
            log(f"[MONEY ACTION] Transferred {amount} to {other_name}. New balance: {new_bal}")
            if feedback_fn:
                feedback_fn(msg)
        else:
            # Add money to household
            if hasattr(funds, "add"):
                try:
                    funds.add(amount, reason, host_sim)
                except TypeError:
                    funds.add(amount, reason)
            elif hasattr(funds, "modify_funds"):
                funds.modify_funds(amount)

            new_bal = getattr(funds, "money", cur_money + amount)
            title = "💸 Денежный перевод" if not is_en else "💸 Money Transfer"
            msg = (
                f"{other_name} перевел(а) вам {amount:,} §!\nНовый баланс семьи: {new_bal:,} §."
                if not is_en else
                f"{other_name} sent you {amount:,} §!\nNew household balance: {new_bal:,} §."
            )
            show_chat_notification(title, msg)
            log(f"[MONEY ACTION] Received {amount} from {other_name}. New balance: {new_bal}")
            if feedback_fn:
                feedback_fn(msg)

    except Exception as e:
        log_exception("Error in _handle_money_action", e)
        if feedback_fn:
            feedback_fn(f"Error processing money action: {e}")



