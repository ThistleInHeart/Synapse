def _find_best_bed_object(actor_sim_info: Any = None):
    """
    Finds the best bed on the active lot for intimacy.
    Prioritizes double beds, then sorts by distance to the actor Sim.
    Returns TurboGameObject of the bed, or None if no bed is found.
    """
    if services is None:
        return None
    try:
        try:
            from turbolib2.wrappers.game_object.game_object import TurboGameObject
        except Exception:
            from turbolib2.wrappers.game_object import TurboGameObject
        from wickedwhims.sex.animations.animations_sex_locations import get_sex_location_identifier, SexLocationType
    except Exception:
        return None

    obj_mgr = services.object_manager()
    if obj_mgr is None:
        return None

    actor_sim = None
    if actor_sim_info is not None and hasattr(actor_sim_info, "get_sim_instance"):
        actor_sim = actor_sim_info.get_sim_instance()

    beds = []
    for obj in obj_mgr.get_all():
        try:
            turbo_obj = TurboGameObject(obj)
            loc_id_data = get_sex_location_identifier(turbo_obj)
            loc_type = loc_id_data[0] if isinstance(loc_id_data, (tuple, list)) else loc_id_data
            type_name = str(getattr(loc_type, "name", loc_type)).upper()

            is_bed = False
            is_double = False

            if hasattr(SexLocationType, "DOUBLE_BED") and loc_type == SexLocationType.DOUBLE_BED:
                is_bed = True
                is_double = True
            elif hasattr(SexLocationType, "MURPHY_DOUBLE_BED") and loc_type == SexLocationType.MURPHY_DOUBLE_BED:
                is_bed = True
                is_double = True
            elif hasattr(SexLocationType, "SINGLE_BED") and loc_type == SexLocationType.SINGLE_BED:
                is_bed = True
            elif hasattr(SexLocationType, "BUNK_BED") and loc_type == SexLocationType.BUNK_BED:
                is_bed = True
            elif hasattr(SexLocationType, "BED_ROLL") and loc_type == SexLocationType.BED_ROLL:
                is_bed = True
            elif "BED" in type_name:
                is_bed = True
                is_double = ("DOUBLE" in type_name)

            if is_bed:
                dist = 9999.0
                if actor_sim is not None and hasattr(actor_sim, "position") and hasattr(obj, "position"):
                    dist = (obj.position - actor_sim.position).magnitude()
                beds.append((is_double, dist, turbo_obj))
        except Exception:
            continue

    if beds:
        # Sort double beds first (not is_double -> False comes first), then by distance ascending
        beds.sort(key=lambda item: (not item[0], item[1]))
        return beds[0][2]

    return None


def _handle_wicked_sex(guest_sim_info: Any, host_sim_info: Any, feedback_fn: Any = None):
    """
    Executes the 'wicked_sex' intimacy action between host and guest:
    1. Validates WickedWhims is installed.
    2. If guest is not on the active lot (e.g. texting from elsewhere):
       - Displays notification to the player.
       - Starts arrival sequence (InviteOver situation / SimSpawner).
       - Registers an in-game alarm watching for guest arrival.
       - Once instanced on lot, triggers intimacy.
    3. If guest is already present on lot:
       - Triggers intimacy immediately.
    """
    def _msg_out(text: str, level: str = "INFO"):
        log(f"[ACTION EXECUTOR] {text}", level=level)
        if feedback_fn:
            try:
                feedback_fn(f"[ACTION DO] {text}")
            except Exception:
                pass

    if not _is_ww_available():
        err_msg = "WickedWhims is not installed; cannot execute intimacy action." if _is_en() else "Мод WickedWhims не установлен; невозможно выполнить интимное действие."
        _msg_out(err_msg, level="WARN")
        show_chat_notification("WickedWhims", err_msg, is_error=True)
        return

    guest_id = getattr(guest_sim_info, "sim_id", 0)
    active_sim_info = services.active_sim_info() if (services is not None and hasattr(services, "active_sim_info")) else None
    active_id = getattr(active_sim_info, "sim_id", 0)

    # Cannot have intimacy with self
    if guest_id == active_id and host_sim_info is not None and getattr(host_sim_info, "sim_id", 0) == active_id:
        _msg_out("Guest is the active sim; cannot trigger intimacy with self.", level="WARN")
        return

    # Check if guest is currently on the active lot
    guest_inst = guest_sim_info.get_sim_instance(allow_hidden_flags=ALL_HIDDEN_REASONS) if hasattr(guest_sim_info, "get_sim_instance") else None
    if guest_inst is None:
        first_n = getattr(guest_sim_info, "first_name", "") or ("Sim" if _is_en() else "Персонаж")
        is_en = _is_en()
        title = "Intimate Encounter" if is_en else "Интимная встреча"
        msg = f"{first_n} agreed to be intimate and is heading over right now!" if is_en else f"{first_n} соглашается на интимную близость и уже направляется к вам!"

        show_chat_notification(title, msg, sim_info=guest_sim_info)
        _msg_out(f"Guest {first_n} is off-lot; initiated arrival sequence for intimacy.")

        _start_visit_situation(guest_sim_info, host_sim_info, feedback_fn=feedback_fn)
        _register_intimacy_arrival_watcher(guest_sim_info, host_sim_info, feedback_fn=feedback_fn)
        return

    # Guest is already on the lot -> execute immediately
    _msg_out(f"Sim {guest_sim_info.first_name} is already present on lot! Starting intimacy...")
    _execute_wicked_sex_now(guest_sim_info, host_sim_info, feedback_fn=feedback_fn)


def _register_intimacy_arrival_watcher(guest_sim_info: Any, host_sim_info: Any, feedback_fn: Any = None):
    """
    Registers an in-game alarm watching for the guest Sim to be physically instanced on the active lot.
    Once arrived, triggers the intimacy action.
    """
    if alarms is None or create_time_span is None or services is None:
        return

    guest_id = getattr(guest_sim_info, "sim_id", 0)
    if guest_id in _INTIMACY_WATCHERS:
        try:
            alarms.cancel_alarm(_INTIMACY_WATCHERS[guest_id])
        except Exception:
            pass
        _INTIMACY_WATCHERS.pop(guest_id, None)

    zone_inst = services.current_zone()
    if zone_inst is None:
        return

    ticks_count = [0]

    def _check_arrival(alarm_handle):
        ticks_count[0] += 1
        inst = guest_sim_info.get_sim_instance(allow_hidden_flags=ALL_HIDDEN_REASONS) if hasattr(guest_sim_info, "get_sim_instance") else None
        if inst is not None:
            try:
                alarms.cancel_alarm(alarm_handle)
            except Exception:
                pass
            _INTIMACY_WATCHERS.pop(guest_id, None)
            log(f"[ACTION EXECUTOR] Guest {guest_sim_info.first_name} arrived on lot for intimacy! Triggering WW sex now.")
            _execute_wicked_sex_now(guest_sim_info, host_sim_info, feedback_fn=feedback_fn)
            return

        # Timeout after 45 in-game minutes
        if ticks_count[0] >= 45:
            try:
                alarms.cancel_alarm(alarm_handle)
            except Exception:
                pass
            _INTIMACY_WATCHERS.pop(guest_id, None)
            log(f"[ACTION EXECUTOR] Intimacy arrival watcher timed out for {guest_sim_info.first_name}.", level="WARN")

    time_span = create_time_span(minutes=1)
    alarm_handle = alarms.add_alarm(
        zone_inst,
        time_span,
        _check_arrival,
        repeating=True,
        use_sleep_time=True,
    )
    _INTIMACY_WATCHERS[guest_id] = alarm_handle


